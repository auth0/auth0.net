    /// <summary>
    /// Retrieve a paginated list of segments for the tenant.
    /// </summary>
    /// <example><code>
    /// await client.Experimentation.Segments.ListAsync(
    ///     new ListSegmentsRequestParameters
    ///     {
    ///         From = "from",
    ///         Take = 1,
    ///         Type = SegmentTypeFilterEnum.Auth0,
    ///     }
    /// );
    /// </code></example>
    public async Task<Pager<Segment>> ListAsync(
        ListSegmentsRequestParameters request,
        RequestOptions? options = null,
        CancellationToken cancellationToken = default
    )
    {
        if (request is not null)
        {
            request = request with { };
        }
        var pager = await CursorPager<
            ListSegmentsRequestParameters,
            RequestOptions?,
            ListSegmentsResponseContent,
            string?,
            Segment
        >
            .CreateInstanceAsync(
                request,
                options,
                async (request, options, cancellationToken) =>
                    await ListInternalAsync(request, options, cancellationToken).WithRawResponse(),
                (request, cursor) =>
                {
                    request.From = cursor;
                },
                response => response.Next,
                response => response.Segments?.ToList(),
                cancellationToken
            )
            .ConfigureAwait(false);
        return pager;
    }

